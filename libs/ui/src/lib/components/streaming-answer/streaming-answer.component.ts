import { ChangeDetectionStrategy, Component, computed, input, output } from '@angular/core';
import { ICON_SIZE } from '../icon/models/icon-size.const';
import { IconComponent } from '../icon/icon.component';
import type { StreamingCiteLabel } from './models/streaming-cite-label.type';
import type { StreamingPart } from './models/streaming-part.type';
import { STREAMING_PART_KIND } from './models/streaming-part-kind.const';
import type { StreamingSegment } from './models/streaming-segment.type';

/**
 * An Ask your shelf answer (StreamingAnswer spec): the question as a bubble, the answer (with a
 * small spark avatar) as plain text with numbered citation buttons, a caret while it streams (or a
 * status pill while the assistant works and no text arrives), and the disclaimer line once it is
 * complete. Content projected into `[uiStreamingLive]` (link cards) shows right under the text as
 * it arrives; sources and actions in the default slot show after the disclaimer, only when the
 * answer is complete.
 *
 * Deviation from the spec (AI-4 plan 5): `segments` instead of `text` + `citations`, because the
 * server already decides where citations sit. Text is rendered by interpolation only (no HTML, no
 * Markdown); line breaks in the text are kept. A citation listed in `disabledCites` (its link was
 * trashed meanwhile) renders disabled.
 *
 * Screen readers: the visible answer is not a live region (it would read every token); a visually
 * hidden polite region announces the whole answer once, when `streaming` turns false.
 */
@Component({
  selector: 'ui-streaming-answer',
  imports: [IconComponent],
  changeDetection: ChangeDetectionStrategy.OnPush,
  host: { class: 'ui-streaming-answer', '[attr.aria-busy]': 'streaming() || null' },
  templateUrl: './streaming-answer.component.html',
  styleUrl: './streaming-answer.component.scss',
})
export class StreamingAnswerComponent {
  protected readonly STREAMING_PART_KIND = STREAMING_PART_KIND;
  protected readonly ICON_SIZE = ICON_SIZE;

  /** The user's question, shown as a bubble. */
  readonly question = input.required<string>();
  /** The answer so far, in reading order. */
  readonly segments = input<readonly StreamingSegment[]>([]);
  /** Text is still arriving: caret on, disclaimer and projected content hidden. */
  readonly streaming = input(false);
  /** Accessible name of a citation button, translated ("Source 2"). */
  readonly citeLabel = input.required<StreamingCiteLabel>();
  /** Citations without a source (trashed meanwhile): rendered disabled. */
  readonly disabledCites = input<readonly number[]>([]);
  /** The disclaimer under every complete answer ("Generated by AI from your links, …"). */
  readonly disclaimer = input.required<string>();
  /**
   * What the assistant is doing while no text streams ("Searching your links…"): a pill under the
   * spark, announced politely; `null` hides it. Shown only while `streaming`.
   */
  readonly status = input<string | null>(null);
  /**
   * Content besides the text is projected into `[uiStreamingLive]` (link cards): the reply shows
   * even without answer text, and the disclaimer under it once complete.
   */
  readonly hasContent = input(false);

  /** A citation button was pressed: its number. */
  readonly citationClicked = output<number>();

  protected readonly parts = computed<readonly StreamingPart[]>(() => {
    const disabled = new Set(this.disabledCites());
    return this.segments().map((segment) =>
      'cite' in segment
        ? {
            kind: STREAMING_PART_KIND.Cite,
            n: segment.cite,
            disabled: disabled.has(segment.cite),
          }
        : { kind: STREAMING_PART_KIND.Text, text: segment.text },
    );
  });

  /** Some answer text arrived (a bare question shows no answer block). */
  protected readonly hasAnswer = computed(() => this.segments().length > 0);
  /** The reply block shows: text, projected live content, or a stream in progress. */
  protected readonly hasReply = computed(
    () => this.hasAnswer() || this.hasContent() || this.streaming(),
  );
  /** The status pill: only while streaming and set. */
  protected readonly shownStatus = computed(() => (this.streaming() ? this.status() : null));

  /** The complete answer as plain text for the live region; empty while streaming. */
  protected readonly announcement = computed(() => {
    if (this.streaming()) {
      return '';
    }
    const label = this.citeLabel();
    return this.segments()
      .map((segment) => ('cite' in segment ? ` (${label(segment.cite)})` : segment.text))
      .join('')
      .replace(/\s+/gu, ' ')
      .trim();
  });
}
