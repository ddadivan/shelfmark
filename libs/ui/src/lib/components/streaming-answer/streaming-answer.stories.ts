import type { Meta, StoryObj } from '@storybook/angular-vite';
import { THEME, THEME_ATTRIBUTE } from '../../models/theme';
import type { StreamingSegment } from './models/streaming-segment.type';
import { StreamingAnswerComponent } from './streaming-answer.component';

const ANSWER: readonly StreamingSegment[] = [
  { text: 'You saved three ramen recipes. The quickest is the weeknight ramen ' },
  { cite: 1 },
  {
    text: ', about 30 minutes with store-bought stock. For a weekend project there is a tonkotsu ',
  },
  { cite: 2 },
  { text: ', and a miso ramen that sits in between ' },
  { cite: 3 },
  { text: '.' },
];
const citeLabel = (n: number): string => `Source ${n}`;

const meta: Meta<StreamingAnswerComponent> = {
  title: 'Components/StreamingAnswer',
  component: StreamingAnswerComponent,
  tags: ['autodocs'],
  parameters: {
    docs: {
      description: {
        component:
          'An Ask your shelf answer: the question bubble, plain text with numbered citation buttons, a caret ' +
          'while streaming (or the shimmering status line under the finished steps while the assistant works), live content such as link cards ' +
          'under the text, and the disclaimer plus the projected sources once complete. The whole answer is ' +
          'announced once, when it completes.',
      },
    },
  },
  args: {
    question: 'Which ramen recipes did I save?',
    segments: ANSWER,
    streaming: false,
    citeLabel,
    disabledCites: [],
    disclaimer: 'Generated by AI from your links, may be inaccurate.',
    status: null,
    steps: [],
    hasContent: false,
  },
  argTypes: { citationClicked: { action: 'citationClicked' } },
  render: (args) => ({
    props: args,
    template: `
      <div style="max-width: 27.5rem">
        <ui-streaming-answer
          [question]="question"
          [segments]="segments"
          [streaming]="streaming"
          [citeLabel]="citeLabel"
          [disabledCites]="disabledCites"
          [disclaimer]="disclaimer"
          [status]="status"
          [steps]="steps"
          [hasContent]="hasContent"
          (citationClicked)="citationClicked($event)"
        >
          @if (hasContent) {
            <p uiStreamingLive style="margin: 0; padding: 0.75rem; border: 1px solid var(--border); border-radius: 0.75rem">Link cards</p>
          }
          <p style="margin: 0; font-size: 0.75rem; color: var(--text-muted)">Sources from your shelf</p>
        </ui-streaming-answer>
      </div>`,
  }),
};

export default meta;
type Story = StoryObj<StreamingAnswerComponent>;

/** Complete: disclaimer and the projected sources. */
export const Complete: Story = {};

/** Streaming: the caret follows the text (no blink under reduced motion). */
export const Streaming: Story = { args: { segments: ANSWER.slice(0, 4), streaming: true } };

/** Waiting for the first text. */
export const Waiting: Story = { args: { segments: [], streaming: true } };

/** Working: a finished step and the shimmering status line while tools run. */
export const Working: Story = {
  args: {
    segments: [],
    streaming: true,
    steps: ['Searched your links · 6 found'],
    status: 'Counting…',
  },
};

/** Live content: cards projected into `[uiStreamingLive]` show under the text as they arrive. */
export const WithCards: Story = {
  args: { segments: [{ text: 'I found 14 links about signals.' }], hasContent: true },
};

/** A cited link was trashed meanwhile: its citation is disabled. */
export const SourceGone: Story = { args: { disabledCites: [2] } };

/** Both themes side by side, streaming and complete. */
export const AllVariants: Story = {
  parameters: { layout: 'padded' },
  render: () => ({
    props: { themes: Object.values(THEME), answer: ANSWER, partial: ANSWER.slice(0, 2), citeLabel },
    template: `
      <div class="ds-themes">
        @for (theme of themes; track theme) {
          <div [attr.${THEME_ATTRIBUTE}]="theme" class="ds-pane">
            <div class="ds-stack" style="max-width: 27.5rem">
              <ui-streaming-answer question="Which ramen recipes did I save?" [segments]="partial" [streaming]="true"
                [citeLabel]="citeLabel" disclaimer="Generated by AI from your links, may be inaccurate." />
              <ui-streaming-answer question="Which ramen recipes did I save?" [segments]="answer"
                [citeLabel]="citeLabel" [disabledCites]="[3]" disclaimer="Generated by AI from your links, may be inaccurate." />
            </div>
          </div>
        }
      </div>`,
  }),
};
