import { TestbedHarnessEnvironment } from '@angular/cdk/testing/testbed';
import { Component, signal } from '@angular/core';
import { TestBed } from '@angular/core/testing';
import type { StreamingSegment } from '../models/streaming-segment.type';
import { StreamingAnswerComponent } from '../streaming-answer.component';
import { UiStreamingAnswerHarness } from './streaming-answer.harness';

@Component({
  imports: [StreamingAnswerComponent],
  template: `
    <ui-streaming-answer
      question="Which ramen recipes did I save?"
      disclaimer="Generated by AI from your links, may be inaccurate."
      [segments]="segments()"
      [streaming]="streaming()"
      [citeLabel]="citeLabel"
      [disabledCites]="[2]"
      [status]="status()"
      (citationClicked)="clicked.set($event)"
    />
  `,
})
class HostComponent {
  readonly segments = signal<readonly StreamingSegment[]>([
    { text: 'The weeknight one ' },
    { cite: 1 },
    { text: ' and the tonkotsu ' },
    { cite: 2 },
    { text: '.' },
  ]);
  readonly streaming = signal(true);
  readonly status = signal<string | null>(null);
  readonly clicked = signal<number | null>(null);
  readonly citeLabel = (n: number): string => `Source ${n}`;
}

describe('UiStreamingAnswerHarness', () => {
  it('reads the question, text, citations, caret, disclaimer and announcement', async () => {
    const fixture = TestBed.createComponent(HostComponent);
    const loader = TestbedHarnessEnvironment.loader(fixture);
    const answer = await loader.getHarness(UiStreamingAnswerHarness.with({ question: /ramen/u }));

    expect(await answer.getQuestion()).toBe('Which ramen recipes did I save?');
    expect(await answer.getAnswerText()).toBe('The weeknight one 1 and the tonkotsu 2.');
    expect(await answer.getCitationLabels()).toEqual(['Source 1', 'Source 2']);
    expect(await answer.isCitationDisabled(1)).toBe(true);
    expect(await answer.isStreaming()).toBe(true);
    expect(await answer.getStatus()).toBeNull();
    fixture.componentInstance.status.set('Counting…');
    expect(await answer.getStatus()).toBe('Counting…');
    expect(await answer.isStreaming()).toBe(true);
    fixture.componentInstance.status.set(null);
    expect(await answer.getDisclaimer()).toBeNull();
    expect(await answer.getAnnouncement()).toBe('');

    await answer.clickCitation(0);
    expect(fixture.componentInstance.clicked()).toBe(1);
    await expect(answer.clickCitation(5)).rejects.toThrow('No citation');
    await expect(answer.isCitationDisabled(5)).rejects.toThrow('No citation');

    fixture.componentInstance.streaming.set(false);
    expect(await answer.isStreaming()).toBe(false);
    expect(await answer.getDisclaimer()).toBe(
      'Generated by AI from your links, may be inaccurate.',
    );
    expect(await answer.getAnnouncement()).toBe(
      'The weeknight one (Source 1) and the tonkotsu (Source 2).',
    );
  });

  it('has no answer text before the first segment', async () => {
    const fixture = TestBed.createComponent(HostComponent);
    fixture.componentInstance.segments.set([]);
    fixture.componentInstance.streaming.set(false);
    const answer =
      await TestbedHarnessEnvironment.loader(fixture).getHarness(UiStreamingAnswerHarness);
    expect(await answer.getAnswerText()).toBe('');
    expect(await answer.getDisclaimer()).toBeNull();
  });
});
