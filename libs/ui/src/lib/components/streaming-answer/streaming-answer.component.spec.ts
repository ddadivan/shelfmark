import { Component, signal } from '@angular/core';
import { TestBed } from '@angular/core/testing';
import { axeViolations } from '../../../testing/axe';
import { compileScss } from '../../../testing/scss';
import type { StreamingSegment } from './models/streaming-segment.type';
import { StreamingAnswerComponent } from './streaming-answer.component';

const HOSTILE = '<img src=x onerror=alert(1)> **bold** [link](https://evil.example)';

@Component({
  imports: [StreamingAnswerComponent],
  template: `
    <ui-streaming-answer
      [question]="question()"
      disclaimer="Generated by AI from your links, may be inaccurate."
      [segments]="segments()"
      [streaming]="streaming()"
      [citeLabel]="citeLabel"
      [disabledCites]="disabled()"
      [status]="status()"
      [hasContent]="cards()"
      (citationClicked)="clicks.update((c) => [...c, $event])"
    >
      @if (cards()) {
        <ul uiStreamingLive class="cards" aria-label="Links found">
          <li>Signals guide</li>
        </ul>
      }
      <ul class="sources" aria-label="Sources from your shelf">
        <li>Weeknight ramen</li>
      </ul>
    </ui-streaming-answer>
  `,
})
class HostComponent {
  readonly question = signal('Which ramen recipes did I save?');
  readonly segments = signal<readonly StreamingSegment[]>([]);
  readonly streaming = signal(true);
  readonly disabled = signal<readonly number[]>([]);
  readonly clicks = signal<number[]>([]);
  readonly status = signal<string | null>(null);
  readonly cards = signal(false);
  readonly citeLabel = (n: number): string => `Source ${n}`;
}

function setup() {
  const fixture = TestBed.createComponent(HostComponent);
  fixture.detectChanges();
  const host = fixture.nativeElement as HTMLElement;
  const update = (apply: (c: HostComponent) => void) => {
    apply(fixture.componentInstance);
    fixture.detectChanges();
  };
  return { fixture, host, update, cmp: fixture.componentInstance };
}

describe('ui-streaming-answer', () => {
  it('shows the question bubble and a caret while waiting for the first text', () => {
    const { host } = setup();
    expect(host.querySelector('.ui-streaming-answer__bubble')?.textContent).toBe(
      'Which ramen recipes did I save?',
    );
    expect(host.querySelector('.ui-streaming-answer__caret')?.getAttribute('aria-hidden')).toBe(
      'true',
    );
    expect(host.querySelector('ui-streaming-answer')?.getAttribute('aria-busy')).toBe('true');
    expect(host.querySelector('.ui-streaming-answer__disclaimer')).toBeNull();
    expect(host.querySelector('.sources')).toBeNull();
  });

  it('renders text by interpolation and citations as labelled buttons', () => {
    const { host, update, cmp } = setup();
    update((c) =>
      c.segments.set([
        { text: 'Quickest is the weeknight ramen ' },
        { cite: 1 },
        { text: ', and a tonkotsu ' },
        { cite: 2 },
        { text: '.' },
      ]),
    );
    const cites = host.querySelectorAll<HTMLButtonElement>('.ui-streaming-answer__cite');
    expect([...cites].map((c) => c.getAttribute('aria-label'))).toEqual(['Source 1', 'Source 2']);
    expect([...cites].map((c) => c.type)).toEqual(['button', 'button']);
    cites[1]?.click();
    cites[0]?.click();
    expect(cmp.clicks()).toEqual([2, 1]);
    expect(host.querySelector('.ui-streaming-answer__text')?.textContent).toBe(
      'Quickest is the weeknight ramen 1, and a tonkotsu 2.',
    );
  });

  it('never turns answer text into markup', () => {
    const { host, update } = setup();
    update((c) => {
      c.segments.set([{ text: HOSTILE }]);
      c.streaming.set(false);
    });
    const text = host.querySelector('.ui-streaming-answer__text');
    expect(text?.textContent).toBe(HOSTILE);
    expect(text?.querySelector('img, a, strong, b')).toBeNull();
  });

  it('disables a citation whose source is gone', () => {
    const { host, update, cmp } = setup();
    update((c) => {
      c.segments.set([{ text: 'Gone ' }, { cite: 1 }]);
      c.disabled.set([1]);
    });
    const cite = host.querySelector<HTMLButtonElement>('.ui-streaming-answer__cite');
    expect(cite?.disabled).toBe(true);
    cite?.click();
    expect(cmp.clicks()).toEqual([]);
  });

  it('shows the disclaimer and the projected sources once complete, and announces once', () => {
    const { host, update } = setup();
    const live = () => host.querySelector('.ui-streaming-answer__live');
    expect(live()?.getAttribute('aria-live')).toBe('polite');
    update((c) => c.segments.set([{ text: 'You saved three. ' }]));
    update((c) => c.segments.set([{ text: 'You saved three. ' }, { cite: 1 }]));
    expect(live()?.textContent).toBe('');
    expect(host.querySelector('.ui-streaming-answer__text')?.getAttribute('aria-live')).toBeNull();

    update((c) => c.streaming.set(false));
    expect(live()?.textContent).toBe('You saved three. (Source 1)');
    expect(host.querySelector('.ui-streaming-answer__caret')).toBeNull();
    expect(host.querySelector('.ui-streaming-answer__disclaimer')?.textContent).toBe(
      'Generated by AI from your links, may be inaccurate.',
    );
    expect(host.querySelector('.sources')).not.toBeNull();
    expect(host.querySelector('ui-streaming-answer')?.getAttribute('aria-busy')).toBeNull();
  });

  it('shows the status pill in a polite region while working, instead of the caret', () => {
    const { host, update } = setup();
    const region = () => host.querySelector('.ui-streaming-answer__status');
    expect(region()?.getAttribute('role')).toBe('status');
    expect(host.querySelector('.ui-streaming-answer__pill')).toBeNull();
    update((c) => c.status.set('Searching your links…'));
    expect(host.querySelector('.ui-streaming-answer__pill')?.textContent).toBe(
      'Searching your links…',
    );
    expect(host.querySelector('.ui-streaming-answer__caret')).toBeNull();
    update((c) => c.segments.set([{ text: 'Found it.' }]));
    expect(host.querySelector('.ui-streaming-answer__text')?.textContent).toContain('Found it.');
    update((c) => c.streaming.set(false));
    expect(host.querySelector('.ui-streaming-answer__pill')).toBeNull();
  });

  it('shows live content as it arrives and keeps the reply for a cards-only answer', () => {
    const { host, update } = setup();
    update((c) => c.cards.set(true));
    expect(host.querySelector('.ui-streaming-answer__extra .cards')).not.toBeNull();
    expect(host.querySelector('.sources')).toBeNull();
    update((c) => c.streaming.set(false));
    expect(host.querySelector('.ui-streaming-answer__extra .cards')).not.toBeNull();
    expect(host.querySelector('.ui-streaming-answer__disclaimer')).not.toBeNull();
    expect(host.querySelector('.sources')).not.toBeNull();
  });

  it('sweeps the pill with the shimmer loop, which stops under reduced motion', () => {
    const css = compileScss('lib/components/streaming-answer/streaming-answer.component.scss');
    expect(css).toMatch(/\.ui-streaming-answer__pill\s*\{[^}]*background: var\(--ai-fill\)/);
    expect(css).toMatch(/\.ui-streaming-answer__pill::after\s*\{[^}]*animation: ui-shimmer/);
  });

  it('swaps and shimmers the words of the pill with a resting colour that keeps contrast on ai-fill', () => {
    const css = compileScss('lib/components/streaming-answer/streaming-answer.component.scss');
    expect(css).toContain(
      '--ui-text-swap-rest: color-mix(in srgb, var(--text) 75%, var(--text-muted))',
    );
    const { host, update } = setup();
    update((c) => c.status.set('Searching your links…'));
    expect(
      host.querySelector('.ui-streaming-answer__pill .ui-text-swap__text--shimmer'),
    ).not.toBeNull();
  });

  it('shows only the bubble for a question without an answer', () => {
    const { host, update } = setup();
    update((c) => c.streaming.set(false));
    expect(host.querySelector('.ui-streaming-answer__text')).toBeNull();
    expect(host.querySelector('.ui-streaming-answer__disclaimer')).toBeNull();
  });

  it('blinks the ai caret in steps and stops it under reduced motion', () => {
    const css = compileScss('lib/components/streaming-answer/streaming-answer.component.scss');
    expect(css).toMatch(/\.ui-streaming-answer__caret\s*\{[^}]*background: var\(--ai\)/);
    expect(css).toMatch(/animation: ui-streaming-caret 1s steps\(2, start\) infinite/);
    expect(css).toMatch(
      /prefers-reduced-motion: reduce\)\s*\{\s*\.ui-streaming-answer__caret\s*\{\s*animation: none/,
    );
    expect(css).toMatch(/data-motion=reduced|data-motion='reduced'/);
  });

  it('has no axe violations while streaming and when complete', async () => {
    const { host, update } = setup();
    update((c) => c.segments.set([{ text: 'You saved three ' }, { cite: 1 }]));
    expect(await axeViolations(host)).toEqual([]);
    update((c) => c.streaming.set(false));
    expect(await axeViolations(host)).toEqual([]);
  });
});
