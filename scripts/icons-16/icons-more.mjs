/** Arc of the wifi mark minus the part within 2.4px of the slash (the line y = x), as stroked pieces. */
const wifiArc = (cx, cy, r, from, to) => {
  const at = (deg) => [
    cx + r * Math.cos((deg * Math.PI) / 180),
    cy + r * Math.sin((deg * Math.PI) / 180),
  ];
  const free = (deg) => Math.abs(at(deg)[0] - at(deg)[1]) / Math.SQRT2 >= 2.4;
  const pieces = [];
  let start = null;
  for (let deg = from; deg <= to + 0.5; deg += 0.5) {
    if (free(deg) && start === null) {
      start = deg;
    }
    if ((!free(deg) || deg + 0.5 > to) && start !== null) {
      pieces.push([start, free(deg) ? deg : deg - 0.5]);
      start = null;
    }
  }
  return pieces
    .filter(([a, b]) => ((b - a) * Math.PI * r) / 180 >= 1.2)
    .map(([a, b]) => {
      const [x0, y0] = at(a).map((v) => Math.round(v * 100) / 100);
      const [x1, y1] = at(b).map((v) => Math.round(v * 100) / 100);
      return stroke(`M${x0} ${y0}A${r} ${r} 0 0 1 ${x1} ${y1}`);
    })
    .join('');
};
