// 16px redraws, batch 1: the interface icons. Centre lines on the 16 grid, 1.5px stroke.
// Rule of thumb: a stroke centre on .25 / .75 puts one edge of the 1.5px line on a pixel boundary,
// so long straight lines are one solid pixel row plus one half-tone row.
import { circle, dot, fill, rect, rounded, stroke } from './stroker.mjs';

const s = (d) => stroke(d);
const poly = (points, r = 0, closed = false) => stroke(rounded(points, r, closed));
const solid = (points, r = 0) => fill(rounded(points, r, true));
/** Scales an absolute M / L / A path about the grid centre (8, 8). */
const scale = (d, k) => {
  const tokens = d.match(/[MLA]|-?\d*\.?\d+/g);
  const out = [];
  let command = '';
  let index = 0;
  for (const token of tokens) {
    if (/[MLA]/.test(token)) {
      command = token;
      index = 0;
      out.push(token);
      continue;
    }
    const n = Number(token);
    const arcFlag = command === 'A' && index % 7 >= 2 && index % 7 <= 4;
    const isX = command === 'A' ? index % 7 === 5 : index % 2 === 0;
    const isRadius = command === 'A' && index % 7 < 2;
    let value = n;
    if (isRadius) {
      value = n * k;
    } else if (!arcFlag) {
      value = 8 + (n - 8) * k;
    }
    void isX;
    out.push(String(Math.round(value * 100) / 100));
    index += 1;
  }
  return out.join(' ').replace(/([MLA]) /g, '$1');
};

