import type { Locator, Page } from '@playwright/test';
import { E2E_TAG } from './models/e2e-tag.const';
import { seedSession } from './support/mock-session';
import { SEARCH_BUTTON, SEARCH_FIELD_NAME } from './support/search-button';
import { expect, test } from './support/test';

// Same values as MOCK_LINKS_SCENARIO_KEY / Showcase and MOCK_AI_STORAGE_KEY in apps/web: the mock
// starts from the demo library (with the AI-4 ramen and coat links), the AI account from here.
const SCENARIO_KEY = 'sm-mock-links-scenario';
const SHOWCASE = 'showcase';
const MOCK_AI_KEY = 'sm-mock-ai';
const SEEDED_FLAG = 'ai-ask-seeded';
const DISCLAIMER = 'Generated by AI, may be inaccurate';
const RAMEN = 'Which ramen recipes did I save?';
/** The mobile shell (tab bar, search dialog with Search · Ask) is below 64em. */
const COMPACT_MAX_PX = 1024;

/** Signed in on All links of the demo library, AI and Ask on (AI pack, 15 questions a day). */
async function openLibrary(page: Page): Promise<void> {
  const account = { settings: { enabled: true, ask: true }, introSeen: true };
  await page.addInitScript(
    ([scenarioKey, scenario, key, flag, value]) => {
      sessionStorage.setItem(scenarioKey, scenario);
      if (!sessionStorage.getItem(flag)) {
        sessionStorage.setItem(flag, '1');
        localStorage.setItem(key, value);
      }
    },
    [SCENARIO_KEY, SHOWCASE, MOCK_AI_KEY, SEEDED_FLAG, JSON.stringify(account)],
  );
  await seedSession(page);
  await page.goto('/links');
  await expect(page.locator('ui-card').first()).toBeVisible();
}

/** Opens the Ask drawer from the header spark button. */
async function openPanel(page: Page): Promise<Locator> {
  await page.getByRole('button', { name: 'Ask your shelf' }).click();
  const panel = page.getByRole('dialog', { name: 'Ask your shelf' });
  await expect(panel).toBeVisible();
  return panel;
}

async function ask(scope: Locator, question: string): Promise<void> {
  await scope.getByRole('textbox', { name: 'Ask about your links' }).fill(question);
  await scope.getByRole('textbox', { name: 'Ask about your links' }).press('Enter');
}

test.describe('Ask your shelf (AI-4, mock API)', () => {
  test.skip(!!process.env['BASE_URL'], 'deployed builds have no mock APIs');

  test('streams a cited answer with sources; a citation highlights its row', async ({ page }) => {
    await openLibrary(page);
    const panel = await openPanel(page);
    await expect(panel).toContainText('What do you want to find out?');
    await expect(panel).toContainText('15 questions left today');
    await expect(panel.getByRole('button', { name: /^What did I save about / })).toBeVisible();

    await ask(panel, RAMEN);
    await expect(panel.getByRole('button', { name: 'Stop' })).toBeVisible();
    await expect(panel).toContainText('You saved a few ramen recipes.');
    await expect(panel).toContainText(DISCLAIMER);
    const sources = panel.getByRole('list', { name: 'Sources from your shelf' });
    await expect(sources.getByRole('listitem')).toHaveCount(3);
    await expect(sources).toContainText(/ramen/i);
    await expect(panel).toContainText('14 questions left today');

    await panel.getByRole('button', { name: 'Source 2' }).click();
    await expect(sources.getByRole('listitem').nth(1).locator('[aria-current="true"]')).toHaveCount(
      1,
    );
    // The panel stays a plain-text answer: no links or images inside the answer text.
    await expect(panel.locator('ui-streaming-answer p a, ui-streaming-answer p img')).toHaveCount(
      0,
    );
  });

  test('says when the links do not answer, shows the limit and recovers from a failure', async ({
    page,
  }) => {
    await openLibrary(page);
    const panel = await openPanel(page);
    await ask(panel, 'What did I save about sourdough?');
    await expect(
      panel.getByRole('button', { name: /^Search “What did I save about sourdough\?”/ }),
    ).toBeVisible();

    await ask(panel, 'ramen ai-fail');
    await expect(panel).toContainText('Couldn’t get an answer right now.');
    await panel.getByRole('button', { name: 'Try again' }).click();
    await expect(panel).toContainText('Couldn’t get an answer right now.');

    await ask(panel, 'ramen ai-quota');
    await expect(panel).toContainText('You’ve used today’s questions.');
    await expect(panel.getByRole('textbox', { name: 'Ask about your links' })).toBeDisabled();
  });

  test('asks from the end of the search results (⌘K row)', async ({ page }) => {
    await openLibrary(page);
    const field = page.getByRole('combobox', { name: SEARCH_FIELD_NAME });
    await field.fill('ramen recipes');
    await page.getByRole('option', { name: 'Ask your shelf: “ramen recipes”' }).click();
    const panel = page.getByRole('dialog', { name: 'Ask your shelf' });
    await expect(panel).toContainText('You saved a few ramen recipes.');
  });

  test(
    'Search · Ask on the phone: the Ask segment and "Ask your shelf about this"',
    { tag: E2E_TAG.Mobile },
    async ({ page }) => {
      test.skip((page.viewportSize()?.width ?? 0) >= COMPACT_MAX_PX, 'the mobile shell only');
      await openLibrary(page);
      await page.getByRole('button', { name: SEARCH_BUTTON }).first().click();
      const dialog = page.getByRole('dialog');
      await dialog.getByRole('combobox', { name: SEARCH_FIELD_NAME }).fill('ramen recipes');
      await dialog.getByRole('option', { name: 'Ask your shelf about this' }).click();
      await expect(dialog.getByRole('heading', { name: 'Ask your shelf' })).toBeVisible();
      await expect(dialog).toContainText('You saved a few ramen recipes.');
      await expect(dialog.getByRole('list', { name: 'Sources from your shelf' })).toBeVisible();

      await dialog.getByRole('radio', { name: 'Search' }).check({ force: true });
      await expect(dialog.getByRole('combobox', { name: SEARCH_FIELD_NAME })).toBeVisible();
      await dialog.getByRole('radio', { name: 'Ask' }).check({ force: true });
      await expect(dialog).toContainText('You saved a few ramen recipes.');
    },
  );
});
