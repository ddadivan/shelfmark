import { expect, type Locator, type Page } from '@playwright/test';
import { isCompact, tabBar } from './sidebar';
import { openSettingsPage } from './mock-session';

// Same value as MOCK_AI_STORAGE_KEY (apps/web/src/app/features/ai/mock/models); the e2e project
// cannot import from apps/web.
const MOCK_AI_KEY = 'sm-mock-ai';
const AI_SEEDED_FLAG = 'ai-seeded';

/** Mirrors MOCK_AI_URL_MARKER: parts of a URL that make the mock AI fail on purpose. */
export const MOCK_AI_URL = {
  /** "Not available right now". */
  fail: 'https://example.org/ai-fail',
  /** The monthly limit. */
  quota: 'https://example.org/ai-quota',
} as const;

/**
 * A URL the mock AI answers with the folder "Angular", the existing tag "docs" and the new tag
 * "example" (the site's name), from the mock library's names (`mockAiOutcome`).
 */
export const AI_URL = 'https://example.org/angular-docs';
export const AI_TITLE = 'Page on example.org';
/** The summary the mock AI writes for `AI_URL` (its title is the mock preview's). */
export const AI_SUMMARY = `${AI_TITLE}. A page from example.org, kept here so you can find it again later.`;
export const AI_DISCLAIMER = 'Generated by AI, may be inaccurate';
/** Draft suggestions take preview (0.7 s), draft (0.4 s), a poll (1 s) and the job (1.2 s). */
export const AI_WAIT = { timeout: 10_000 } as const;

/** AI mode values of the mock account (mirror AI_FEATURE_MODE). */
export type AiMode = 'suggest' | 'auto' | 'off';

export interface AiSeed {
  enabled?: boolean;
  folderMode?: AiMode;
  tagsMode?: AiMode;
  summaries?: boolean;
}

/**
 * Stores the mock account's AI settings before the app starts (once: a reload keeps what the app
 * saved since). AI on with the intro seen by default; a regular mock account otherwise starts off.
 */
export async function seedAi(page: Page, settings: AiSeed = { enabled: true }): Promise<void> {
  await page.addInitScript(
    ([key, flag, account]) => {
      if (!sessionStorage.getItem(flag)) {
        sessionStorage.setItem(flag, '1');
        localStorage.setItem(key, account);
      }
    },
    [
      MOCK_AI_KEY,
      AI_SEEDED_FLAG,
      JSON.stringify({ settings: { enabled: true, ...settings }, introSeen: true }),
    ],
  );
}

/** Opens Settings › AI in the app (the in-memory mock library stays): the nav, or You › AI. */
export async function openAiSettings(page: Page): Promise<void> {
  await openSettingsPage(page);
  if (isCompact(page)) {
    await page.getByRole('main').getByRole('link', { name: /^AI\b/ }).click();
  } else {
    await page
      .getByRole('navigation', { name: 'Settings' })
      .getByRole('link', { name: 'AI', exact: true })
      .click();
  }
  await expect(page.getByRole('heading', { level: 1, name: 'AI' })).toBeVisible();
}

/** Back from Settings to All links without a reload (a reload would reset the mock library). */
export async function backToLinks(page: Page): Promise<void> {
  if (isCompact(page)) {
    await tabBar(page).getByRole('link', { name: 'Library' }).click();
    await page
      .locator('app-library-tile')
      .getByRole('link', { name: /^All links\b/ })
      .click();
  } else {
    await page
      .getByRole('navigation', { name: 'Settings' })
      .getByRole('link', { name: 'Back to links' })
      .click();
  }
  await expect(page.locator('ui-card').first()).toBeVisible();
}

/** Opens Add link and pastes `url`; resolves once the preview filled the title. */
export async function addLinkWith(page: Page, url: string): Promise<Locator> {
  await page.getByRole('button', { name: 'Add link' }).first().click();
  const dialog = page.getByRole('dialog', { name: 'Add link' });
  await expect(dialog).toBeVisible();
  await dialog.getByLabel('Link', { exact: true }).fill(url);
  await expect(dialog.getByLabel('Title', { exact: true })).toHaveValue(/^Page on /);
  return dialog;
}

/** The suggestion toolbar of the tags field ("Suggested tags"). */
export function tagSuggestions(dialog: Locator): Locator {
  return dialog.getByRole('toolbar', { name: 'Suggested tags' });
}

/** The card of the link titled `title`. */
export function cardOf(page: Page, title: string): Locator {
  return page.locator('ui-card').filter({ hasText: title });
}

/** Saves the open Add link dialog (the sheet on a phone has no Cancel, the button is the same). */
export async function saveLink(dialog: Locator): Promise<void> {
  await dialog.getByRole('button', { name: /^Save( link| anyway)$/ }).click();
  await expect(dialog).toBeHidden();
}
