import type { Locator, Page } from '@playwright/test';
import { E2E_TAG } from './models/e2e-tag.const';
import { openAiSettings } from './support/ai';
import { seedSession } from './support/mock-session';
import { openSearchDialog, SEARCH_FIELD_NAME } from './support/search-button';
import { isCompact } from './support/sidebar';
import { expect, test } from './support/test';
import { openCardMenu } from './support/card-menu';

// Same values as MOCK_LINKS_SCENARIO_KEY / Showcase and MOCK_AI_STORAGE_KEY in apps/web: the mock
// starts from the demo library (titles, tags, summaries), the AI account from what is stored here.
const SCENARIO_KEY = 'sm-mock-links-scenario';
const SHOWCASE = 'showcase';
const MOCK_AI_KEY = 'sm-mock-ai';
const SEEDED_FLAG = 'ai-search-seeded';
const DISCLAIMER = 'Generated by AI, may be inaccurate';
/** The meaning group of the search list (Shelf block 3). */
const MEANING = 'Close in meaning';

interface Seed {
  enabled?: boolean;
  meaningSearch?: boolean;
  /** The mock's "getting ready" toggle (fewer than 80% of links embedded). */
  searchProcessing?: boolean;
}

/** Signed in on All links of the demo library, with the mock AI account seeded once. */
async function openLibrary(page: Page, seed: Seed = {}): Promise<void> {
  const account = {
    // Ask off (AI-4): its row would end every result list here.
    settings: {
      enabled: seed.enabled ?? true,
      meaningSearch: seed.meaningSearch ?? true,
      ask: false,
    },
    introSeen: true,
    searchProcessing: seed.searchProcessing ?? false,
  };
  await page.addInitScript(
    ([scenarioKey, scenario, key, flag, value]) => {
      sessionStorage.setItem(scenarioKey, scenario);
      if (!sessionStorage.getItem(flag)) {
        sessionStorage.setItem(flag, '1');
        localStorage.setItem(key, value);
      }
    },
    [SCENARIO_KEY, SHOWCASE, MOCK_AI_KEY, SEEDED_FLAG, JSON.stringify(account)],
  );
  await seedSession(page);
  await page.goto('/links');
  await expect(page.locator('ui-card').first()).toBeVisible();
}

/**
 * Searches in the search dialog and resolves with its result list: the Search tab of the mobile
 * shell; from 64em Ctrl+K on a settings page, the only place the header has no field (Shelf
 * block 3; the header field filters the feed, see the feed test below).
 */
async function search(page: Page, text: string): Promise<Locator> {
  if (!isCompact(page)) {
    await page.goto('/settings/account');
  }
  const dialog = await openSearchDialog(page);
  await dialog.getByRole('combobox', { name: SEARCH_FIELD_NAME }).fill(text);
  return dialog.getByRole('listbox', { name: 'Search results' });
}

function group(list: Locator, name: string): Locator {
  return list.getByRole('group', { name });
}

test.describe('search by meaning (AI-3, mock API)', () => {
  test.skip(!!process.env['BASE_URL'], 'deployed builds have no mock APIs');

  test(
    'lists word matches first, then meaning matches under the divider with "Close to"',
    { tag: E2E_TAG.Mobile },
    async ({ page }) => {
      await openLibrary(page);
      const list = await search(page, 'signals');
      const related = group(list, MEANING);
      await expect(related).toBeVisible();
      await expect(list.getByRole('group').first()).not.toHaveAccessibleName(MEANING);
      await expect(
        list.getByRole('option', { name: /Angular signals: the guide angular\.dev in Signals/ }),
      ).toBeVisible();
      const rows = related.getByRole('option');
      await expect(rows.first()).toContainText('Close to:');
      await expect(rows.first().getByRole('img', { name: DISCLAIMER })).toBeVisible();
      // Word matches never repeat under the divider.
      await expect(related.getByRole('option', { name: /Angular signals: the guide/ })).toHaveCount(
        0,
      );
    },
  );

  test('lets meaning matches carry a query with no word matches', async ({ page }) => {
    await openLibrary(page);
    const list = await search(page, 'warm winter clothes');
    await expect(list.getByText('No links with these words')).toBeVisible();
    const related = group(list, MEANING);
    await expect(related.getByRole('option', { name: /Nano Puff jacket/ })).toBeVisible();
    await expect(list.getByRole('group')).toHaveCount(1);
  });

  test('says once that search by meaning is getting ready, with today’s results', async ({
    page,
  }) => {
    await openLibrary(page, { searchProcessing: true });
    const list = await search(page, 'signals');
    await expect(
      list.getByRole('option', { name: /Angular signals: the guide angular\.dev in Signals/ }),
    ).toBeVisible();
    await expect(
      page.getByText(/^Search by meaning is getting ready: \d+ of \d+ links\./),
    ).toBeVisible();
    await expect(group(list, MEANING)).toHaveCount(0);
  });

  test('from 64em the feed search ends with "Close in meaning" cards after the word matches', async ({
    page,
  }) => {
    test.skip(isCompact(page), 'the header field filters the feed from 64em');
    await openLibrary(page);
    await page.getByRole('combobox', { name: SEARCH_FIELD_NAME }).fill('signals');
    await expect(page).toHaveURL(/[?&]q=signals/);
    await expect(page.getByRole('heading', { level: 1, name: 'Search' })).toBeVisible();
    const meaning = page.getByRole('region', { name: /^Close in meaning \d+$/ });
    await expect(meaning).toBeVisible();
    // After the word matches, never repeating them.
    const words = page.getByRole('list', { name: 'Saved links' });
    const [wordsBox, meaningBox] = await Promise.all([words.boundingBox(), meaning.boundingBox()]);
    expect(meaningBox?.y ?? 0).toBeGreaterThan(wordsBox?.y ?? 0);
    await expect(meaning.getByRole('heading', { name: 'Angular signals: the guide' })).toHaveCount(
      0,
    );
  });

  test('is exactly today’s search while AI is off', async ({ page }) => {
    await openLibrary(page, { enabled: false });
    const list = await search(page, 'warm winter clothes');
    await expect(page.getByText('Nothing found for “warm winter clothes”')).toBeVisible();
    await expect(list.getByText(MEANING)).toHaveCount(0);
    await expect(page.getByText('No links with these words')).toHaveCount(0);
  });

  test(
    'Settings › AI turns Search by meaning off and on, with how many links are ready',
    { tag: E2E_TAG.Mobile },
    async ({ page }) => {
      await openLibrary(page);
      await openAiSettings(page);
      const toggle = page.getByRole('switch', { name: 'Search by meaning' });
      await expect(toggle).toBeChecked();
      await expect(page.getByText('Voyage AI').first()).toBeVisible();
      await expect(page.locator('app-meaning-search-control')).toContainText('Ready');
      await toggle.click();
      await expect(toggle).not.toBeChecked();
      await expect(page.locator('app-meaning-search-control')).not.toContainText('Ready');
      await toggle.click();
      await expect(toggle).toBeChecked();
    },
  );

  test(
    'the link preview offers related links and switches to the one chosen (#572)',
    { tag: E2E_TAG.Mobile },
    async ({ page, context }) => {
      // Third-party pages never leave the test machine: framed documents get a tiny local page.
      await context.route(/^https:\/\/(?!localhost|127\.0\.0\.1)/, (route) =>
        route.request().resourceType() === 'document'
          ? route.fulfill({
              contentType: 'text/html',
              body: '<!doctype html><title>Page</title>',
            })
          : route.abort(),
      );
      await openLibrary(page);
      // A real phone taps (pointer and touch events), a desktop clicks.
      const press = async (target: Locator): Promise<void> =>
        test.info().project.use.hasTouch ? target.tap() : target.click();
      const opened: string[] = [];
      context.on('page', (other) => opened.push(other.url()));
      await openCardMenu(page.locator('ui-card').filter({ hasText: 'Nano Puff jacket' }));
      await page.getByRole('menuitem', { name: /Preview here/ }).click();
      await expect(page).toHaveURL(/[?&]preview=/);
      const before = page.url();
      await press(page.getByRole('button', { name: /^Related · \d+$/ }));
      const related = page.getByRole('dialog', { name: 'Related on your shelf' });
      await expect(related).toBeVisible();
      await expect(related).toContainText('Close to:');
      // Up to five rows fit: no scroll either way.
      const scroll = await related.evaluate((element) => {
        const panel = element.closest('.ui-popover__surface') ?? element;
        return {
          sideways: panel.scrollWidth > panel.clientWidth,
          down: panel.scrollHeight > panel.clientHeight,
        };
      });
      expect(scroll).toEqual({ sideways: false, down: false });
      await press(related.getByRole('listitem').first().getByRole('button'));
      await expect(related).toBeHidden();
      await expect(page).toHaveURL(/[?&]preview=/);
      expect(page.url()).not.toBe(before);
      // The chosen link opens here, in the preview, never in a new tab.
      expect(opened).toEqual([]);
    },
  );

  test('Edit link no longer lists related links (#572)', async ({ page }) => {
    await openLibrary(page);
    await openCardMenu(page.locator('ui-card').filter({ hasText: 'Nano Puff jacket' }));
    await page.getByRole('menuitem', { name: 'Edit' }).click();
    const dialog = page.getByRole('dialog', { name: 'Edit link' });
    await expect(dialog.getByRole('textbox', { name: 'Title' })).toBeVisible();
    await expect(dialog.getByText('Related on your shelf')).toHaveCount(0);
  });

  test('reminds about older links AI has not read; Process starts it', async ({ page }) => {
    await openLibrary(page);
    await search(page, 'signals');
    const reminder = page.locator('app-backfill-reminder');
    await expect(reminder).toContainText(/AI hasn’t read \d+ older links? yet/);
    // Outside the listbox: never an option.
    await expect(
      page.getByRole('listbox', { name: 'Search results' }).locator('app-backfill-reminder'),
    ).toHaveCount(0);
    await reminder.getByRole('button', { name: 'Process' }).click();
    await expect(reminder).toContainText('Processing started');
    await expect(reminder).toBeEmpty({ timeout: 5000 });
  });

  test('× hides the older-links reminder for good', async ({ page }) => {
    await openLibrary(page);
    await search(page, 'signals');
    const reminder = page.locator('app-backfill-reminder');
    await expect(reminder).toContainText(/AI hasn’t read/);
    await reminder.getByRole('button', { name: 'Hide' }).click();
    await expect(reminder).toBeEmpty();
    // A new load (the dialog opens on a settings page from 64em) keeps it hidden.
    await page.goto('/links');
    await expect(page.locator('ui-card').first()).toBeVisible();
    await search(page, 'signals');
    await expect(page.getByRole('option').first()).toBeVisible();
    await expect(page.getByText(/AI hasn’t read/)).toHaveCount(0);
  });
});
