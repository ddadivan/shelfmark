import { isoWeek } from './iso-week';

describe('isoWeek', () => {
  it.each([
    ['2026-11-17T12:00:00.000Z', '2026-W47'],
    ['2026-11-16T00:00:00.000Z', '2026-W47'],
    ['2026-11-22T23:59:59.000Z', '2026-W47'],
    ['2026-11-23T00:00:00.000Z', '2026-W48'],
    ['2027-01-01T00:00:00.000Z', '2026-W53'],
    ['2026-01-01T00:00:00.000Z', '2026-W01'],
    ['2024-12-30T00:00:00.000Z', '2025-W01'],
  ])('%s is %s', (at, week) => {
    expect(isoWeek(new Date(at))).toBe(week);
  });
});
