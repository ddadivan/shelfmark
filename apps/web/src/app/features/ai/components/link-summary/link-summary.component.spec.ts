import { TestBed } from '@angular/core/testing';
import { AI_JOB_STATUS, AI_LIMIT, SUMMARY_SOURCE } from '@shelfmark/contracts';
import { loadEnglish, provideTranslocoForTest } from '../../../../testing/transloco-testing';
import type { LinkSummaryItem } from './models/link-summary-item.type';
import { LinkSummaryComponent } from './link-summary.component';

async function setup(link: LinkSummaryItem, row = false) {
  TestBed.configureTestingModule({ providers: [provideTranslocoForTest()] });
  await loadEnglish();
  const fixture = TestBed.createComponent(LinkSummaryComponent);
  fixture.componentRef.setInput('link', link);
  fixture.componentRef.setInput('row', row);
  await fixture.whenStable();
  return { fixture, element: fixture.nativeElement as HTMLElement };
}

describe('LinkSummaryComponent', () => {
  afterEach(() => {
    vi.useRealTimers();
  });

  it('shows the AI summary with the mark that carries the disclaimer', async () => {
    const { element } = await setup({
      summary: 'Why Angular dropped zone.js.',
      summarySource: SUMMARY_SOURCE.Ai,
      aiStatus: AI_JOB_STATUS.Done,
    });
    expect(element.textContent?.trim()).toBe('Why Angular dropped zone.js.');
    const mark = element.querySelector('[role="img"]');
    expect(mark?.getAttribute('aria-label')).toBe('Summary generated by AI, may be inaccurate');
    expect(mark?.getAttribute('title')).toBe('Summary generated by AI, may be inaccurate');
  });

  it('shows skeleton lines right after a save, then nothing once the window has passed', async () => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout', 'Date'] });
    const { fixture, element } = await setup({
      summary: null,
      summarySource: null,
      aiStatus: AI_JOB_STATUS.Pending,
      createdAt: new Date().toISOString(),
    });
    const status = element.querySelector('[role="status"]');
    expect(status?.getAttribute('aria-label')).toBe('Writing a summary');
    expect(status?.getAttribute('aria-busy')).toBe('true');
    expect(element.querySelector('ui-skeleton')).not.toBeNull();

    vi.advanceTimersByTime(AI_LIMIT.PendingSkeletonMs);
    await fixture.whenStable();
    expect(element.querySelector('[role="status"]')).toBeNull();
    expect(element.textContent?.trim()).toBe('');
  });

  it('fades the summary in when it replaces the skeleton', async () => {
    const { fixture, element } = await setup({
      summary: null,
      summarySource: null,
      aiStatus: AI_JOB_STATUS.Pending,
      createdAt: new Date().toISOString(),
    });
    fixture.componentRef.setInput('link', {
      summary: 'A summary.',
      summarySource: SUMMARY_SOURCE.Ai,
      aiStatus: AI_JOB_STATUS.Done,
      createdAt: new Date().toISOString(),
    });
    await fixture.whenStable();
    expect(element.querySelector('.link-summary__body--reveal')?.textContent).toContain(
      'A summary.',
    );
  });

  it('shows no skeleton for an old pending link, a failed job or no summary', async () => {
    const old = await setup({
      summary: null,
      aiStatus: AI_JOB_STATUS.Pending,
      createdAt: new Date(Date.now() - AI_LIMIT.PendingSkeletonMs - 1000).toISOString(),
    });
    expect(old.element.querySelector('ui-skeleton')).toBeNull();
    TestBed.resetTestingModule();
    const failed = await setup({ summary: null, aiStatus: AI_JOB_STATUS.Failed }, true);
    expect(failed.element.textContent?.trim()).toBe('');
    expect(failed.element.classList).toContain('link-summary--row');
  });
});
