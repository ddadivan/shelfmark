import { TestbedHarnessEnvironment } from '@angular/cdk/testing/testbed';
import { ChangeDetectionStrategy, Component, signal } from '@angular/core';
import { TestBed } from '@angular/core/testing';
import { form } from '@angular/forms/signals';
import { SUMMARY_SOURCE, type SummarySource } from '@shelfmark/contracts';
import { UiButtonHarness } from '@shelfmark/ui/testing';
import { axeViolations } from '../../../../../testing/axe';
import { loadEnglish, provideTranslocoForTest } from '../../../../testing/transloco-testing';
import { SummaryFieldComponent } from './summary-field.component';

@Component({
  selector: 'app-summary-field-host',
  imports: [SummaryFieldComponent],
  changeDetection: ChangeDetectionStrategy.OnPush,
  template: `<app-summary-field
    [field]="summary"
    [source]="source()"
    [canRewrite]="canRewrite()"
    [rewriting]="rewriting()"
    (rewrite)="rewrites = rewrites + 1"
  />`,
})
class HostComponent {
  readonly model = signal('Why Angular dropped zone.js.');
  readonly summary = form(this.model);
  readonly source = signal<SummarySource | null>(SUMMARY_SOURCE.Ai);
  readonly canRewrite = signal(true);
  readonly rewriting = signal(false);
  rewrites = 0;
}

async function setup() {
  TestBed.configureTestingModule({ providers: [provideTranslocoForTest()] });
  await loadEnglish();
  const fixture = TestBed.createComponent(HostComponent);
  await fixture.whenStable();
  const loader = TestbedHarnessEnvironment.loader(fixture);
  return {
    fixture,
    loader,
    host: fixture.componentInstance,
    element: fixture.nativeElement as HTMLElement,
  };
}

describe('SummaryFieldComponent', () => {
  it('marks AI text with the badge and the visible disclaimer, and offers Rewrite', async () => {
    const { loader, host, element } = await setup();
    expect(element.querySelector('textarea')?.value).toBe('Why Angular dropped zone.js.');
    expect(element.querySelector('.summary-field__source')?.textContent?.trim()).toBe(
      'Written by AI',
    );
    expect(element.textContent).toContain('Generated by AI, may be inaccurate. Edit it');
    expect(element.querySelector('ui-badge')).toBeNull();
    expect(element.querySelector('.summary-field__source ui-icon[name="spark"]')).not.toBeNull();
    expect(element.querySelector('.ui-button--ai-ghost')).not.toBeNull();
    const rewrite = await loader.getHarness(UiButtonHarness.with({ text: 'Rewrite' }));
    await rewrite.click();
    expect(host.rewrites).toBe(1);
  });

  it('shows the spinner while rewriting', async () => {
    const { fixture, loader, host } = await setup();
    host.rewriting.set(true);
    await fixture.whenStable();
    const rewrite = await loader.getHarness(UiButtonHarness.with({ text: 'Rewrite' }));
    expect(await rewrite.isLoading()).toBe(true);
  });

  it('says whose text it is: the user’s, or nobody’s while empty', async () => {
    const { fixture, loader, host, element } = await setup();
    host.source.set(SUMMARY_SOURCE.User);
    host.canRewrite.set(false);
    await fixture.whenStable();
    expect(element.querySelector('.summary-field__source')?.textContent?.trim()).toBe(
      'Edited by you',
    );
    expect(element.textContent).toContain('Clear the field to let AI write it again.');
    expect(await loader.getAllHarnesses(UiButtonHarness)).toHaveLength(0);

    host.source.set(null);
    host.model.set('');
    await fixture.whenStable();
    expect(element.querySelector('.summary-field__source')).toBeNull();
    expect(element.textContent).toContain('Leave it empty and AI writes one.');
  });

  it('has no axe violations', async () => {
    const { element } = await setup();
    expect(await axeViolations(element)).toEqual([]);
  });
});
